import { render, screen, fireEvent } from '@testing-library/react';
import { expect, it, vi } from 'vitest';
import RoleplayToolPanel from './RoleplayToolPanel';
vi.mock('@/components/map/hooks/useMapData', () => ({ useWorldMaps: () => ({ maps: [] }) }));
vi.mock('./WorldStatePanel', () => ({ default: () => <p>WorldStatePanel</p> }));
vi.mock('./WorldStateEditor', () => ({ default: () => <p>WorldStateEditor</p> }));
vi.mock('./InventoryList', () => ({ default: () => <p>InventoryList</p> }));
vi.mock('./CharacterSheet', () => ({ default: () => <p>CharacterSheet</p> }));
vi.mock('./DiceRoller', () => ({ default: () => <p>DiceRoller</p> }));
vi.mock('./BookmarkList', () => ({ default: () => <p>BookmarkList</p> }));
vi.mock('./BranchSelector', () => ({ default: () => <p>BranchSelector</p> }));
vi.mock('./KnowledgeView', () => ({ default: () => <p>KnowledgeView</p> }));
vi.mock('./ImageGallery', () => ({ default: () => <p>ImageGallery</p> }));
vi.mock('./AgentInsights', () => ({ default: () => <p>AgentInsights</p> }));
vi.mock('./AgentModelSettings', () => ({ default: () => <p>AgentModelSettings</p> }));
vi.mock('./CharacterProposalList', () => ({ default: () => <p>CharacterProposalList</p> }));
vi.mock('./BattleOverlay', () => ({ default: () => <p>BattleOverlay</p> }));
vi.mock('@/components/map/MapEditor', () => ({ default: () => null }));
vi.mock('@/components/map/LocalMapPanel', () => ({ default: () => null }));
vi.mock('@/components/map/WorldMap2D', () => ({ default: () => null }));

it('hides narrator tools and unmounts their active content when the mode is switched off', () => {
  const props = { conversationId: 'story', participants: [] };
  const { rerender } = render(<RoleplayToolPanel {...props} />);
  expect(screen.queryByTitle('AI')).not.toBeInTheDocument();
  expect(screen.queryByTitle('Knowledge')).not.toBeInTheDocument();
  expect(screen.queryByText('WorldStateEditor')).not.toBeInTheDocument();
  fireEvent.click(screen.getByTitle('Bookmarks'));
  expect(screen.getByText('BookmarkList')).toBeInTheDocument();
  expect(screen.queryByText('BranchSelector')).not.toBeInTheDocument();
  rerender(<RoleplayToolPanel {...props} narratorMode />);
  expect(screen.getByText('BranchSelector')).toBeInTheDocument();
  fireEvent.click(screen.getByTitle('AI'));
  expect(screen.getByText('AgentInsights')).toBeInTheDocument();
  expect(screen.getByText('CharacterProposalList')).toBeInTheDocument();
  rerender(<RoleplayToolPanel {...props} narratorMode={false} />);
  expect(screen.queryByText('AgentInsights')).not.toBeInTheDocument();
  expect(screen.queryByText('CharacterProposalList')).not.toBeInTheDocument();
  expect(screen.getByText('WorldStatePanel')).toBeInTheDocument();
});
